CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    identity_key VARCHAR(64) NOT NULL,
    name VARCHAR(100) NOT NULL,
    nickname VARCHAR(20) NOT NULL,
    birth_date DATE,
    gender VARCHAR(20),
    phone_number VARCHAR(20) NOT NULL,
    pin_hash VARCHAR(100) NOT NULL,
    fcm_token VARCHAR(255),
    avatar_file_name VARCHAR(100),
    phone_verified BOOLEAN NOT NULL,
    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL,
    last_login_at TIMESTAMP(6) WITHOUT TIME ZONE,
    required_terms_agreed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    marketing_agreed_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_identity_key UNIQUE (identity_key),
    CONSTRAINT uk_users_phone_number UNIQUE (phone_number)
);

CREATE TABLE auth_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    occurred_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    client_ip VARCHAR(64),
    user_agent VARCHAR(500),
    CONSTRAINT pk_auth_audit_logs PRIMARY KEY (id)
);
