ALTER TABLE accounts
    ADD COLUMN product_code VARCHAR(10),
    ADD COLUMN is_default BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN display_order INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_accounts_display_order_nonnegative
        CHECK (display_order >= 0);

WITH ranked_accounts AS (
    SELECT id,
           (ROW_NUMBER() OVER (PARTITION BY user_id ORDER BY id) - 1)::INTEGER AS display_order,
           MIN(id) FILTER (WHERE active) OVER (PARTITION BY user_id) AS default_account_id
    FROM accounts
)
UPDATE accounts account
SET display_order = ranked.display_order,
    is_default = COALESCE(account.id = ranked.default_account_id, FALSE)
FROM ranked_accounts ranked
WHERE account.id = ranked.id;

CREATE UNIQUE INDEX uk_accounts_user_active_default
    ON accounts (user_id)
    WHERE active = TRUE AND is_default = TRUE;

CREATE TABLE account_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL,
    external_transaction_key VARCHAR(64) NOT NULL,
    transaction_type VARCHAR(20) NOT NULL,
    amount NUMERIC(19, 4) NOT NULL,
    transacted_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    description VARCHAR(500),
    after_balance NUMERIC(19, 4),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_account_transactions PRIMARY KEY (id),
    CONSTRAINT fk_account_transactions_account
        FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE RESTRICT,
    CONSTRAINT uk_account_transactions_account_external_key
        UNIQUE (account_id, external_transaction_key),
    CONSTRAINT ck_account_transactions_external_key_format
        CHECK (external_transaction_key ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_account_transactions_type
        CHECK (transaction_type IN ('EXPENSE', 'INCOME')),
    CONSTRAINT ck_account_transactions_amount_positive
        CHECK (amount > 0)
);

CREATE INDEX idx_account_transactions_account_transacted_at
    ON account_transactions (account_id, transacted_at DESC);

CREATE TABLE account_monthly_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id BIGINT NOT NULL,
    year_month DATE NOT NULL,
    monthly_expense_amount NUMERIC(19, 4) NOT NULL,
    expense_count BIGINT NOT NULL,
    last_used_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_account_monthly_summaries PRIMARY KEY (id),
    CONSTRAINT fk_account_monthly_summaries_account
        FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE RESTRICT,
    CONSTRAINT uk_account_monthly_summaries_account_year_month
        UNIQUE (account_id, year_month),
    CONSTRAINT ck_account_monthly_summaries_year_month_first_day
        CHECK (year_month = DATE_TRUNC('month', year_month)::DATE),
    CONSTRAINT ck_account_monthly_summaries_expense_amount_nonnegative
        CHECK (monthly_expense_amount >= 0),
    CONSTRAINT ck_account_monthly_summaries_expense_count_nonnegative
        CHECK (expense_count >= 0)
);
