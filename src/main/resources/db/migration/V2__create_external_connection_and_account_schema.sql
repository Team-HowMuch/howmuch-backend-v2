CREATE TABLE external_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    connected_id_ciphertext VARCHAR(1024) NOT NULL,
    configuration_fingerprint VARCHAR(64) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_external_connections PRIMARY KEY (id),
    CONSTRAINT uk_external_connections_user_id UNIQUE (user_id),
    CONSTRAINT fk_external_connections_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE connected_institutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    external_connection_id BIGINT NOT NULL,
    organization VARCHAR(10) NOT NULL,
    status VARCHAR(20) NOT NULL,
    last_result_code VARCHAR(30),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_connected_institutions PRIMARY KEY (id),
    CONSTRAINT uk_connected_institution_connection_organization
        UNIQUE (external_connection_id, organization),
    CONSTRAINT fk_connected_institutions_external_connection
        FOREIGN KEY (external_connection_id) REFERENCES external_connections (id)
);

CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    external_connection_id BIGINT NOT NULL,
    organization VARCHAR(10) NOT NULL,
    candidate_key VARCHAR(64) NOT NULL,
    external_account_key_ciphertext VARCHAR(1024) NOT NULL,
    type VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    masked_number VARCHAR(64) NOT NULL,
    balance NUMERIC(19, 4),
    currency VARCHAR(10),
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_accounts PRIMARY KEY (id),
    CONSTRAINT uk_accounts_connection_candidate UNIQUE (external_connection_id, candidate_key),
    CONSTRAINT fk_accounts_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_accounts_external_connection
        FOREIGN KEY (external_connection_id) REFERENCES external_connections (id)
);
