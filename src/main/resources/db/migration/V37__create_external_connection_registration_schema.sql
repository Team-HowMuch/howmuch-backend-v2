CREATE TABLE external_connection_registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    organization VARCHAR(10) NOT NULL,
    operation_kind VARCHAR(20) NOT NULL,
    login_type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    connected_id_ciphertext VARCHAR(1024),
    configuration_fingerprint VARCHAR(64) NOT NULL,
    last_result_code VARCHAR(30),
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_external_connection_registrations PRIMARY KEY (id),
    CONSTRAINT fk_external_connection_registrations_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE UNIQUE INDEX uk_external_connection_registrations_active_user
    ON external_connection_registrations (user_id)
    WHERE status IN ('PENDING', 'UNKNOWN');

CREATE INDEX ix_external_connection_registrations_status_updated_at
    ON external_connection_registrations (status, updated_at);
