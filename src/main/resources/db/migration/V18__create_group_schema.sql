CREATE TABLE groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(20) NOT NULL,
    memo VARCHAR(60),
    image_file_name VARCHAR(100),
    owner_id BIGINT NOT NULL,
    invite_code VARCHAR(8) NOT NULL,
    status VARCHAR(20) NOT NULL,
    creator_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    deleted_at TIMESTAMP(6) WITHOUT TIME ZONE,
    CONSTRAINT pk_groups PRIMARY KEY (id),
    CONSTRAINT uk_groups_invite_code UNIQUE (invite_code),
    CONSTRAINT fk_groups_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_groups_creator FOREIGN KEY (creator_id) REFERENCES users (id),
    CONSTRAINT ck_groups_name_not_blank CHECK (CHAR_LENGTH(BTRIM(name)) > 0),
    CONSTRAINT ck_groups_memo_not_blank CHECK (
        memo IS NULL OR CHAR_LENGTH(BTRIM(memo)) > 0
    ),
    CONSTRAINT ck_groups_invite_code CHECK (invite_code ~ '^[A-Z0-9]{8}$'),
    CONSTRAINT ck_groups_status CHECK (status IN ('ACTIVE', 'DELETED')),
    CONSTRAINT ck_groups_deleted_at CHECK (
        (status = 'ACTIVE' AND deleted_at IS NULL)
        OR (status = 'DELETED' AND deleted_at IS NOT NULL)
    )
);

CREATE INDEX idx_groups_owner
    ON groups (owner_id);

CREATE INDEX idx_groups_status
    ON groups (status);

CREATE TABLE group_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    group_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    joined_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    left_at TIMESTAMP(6) WITHOUT TIME ZONE,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_group_members PRIMARY KEY (id),
    CONSTRAINT uk_group_members_group_user UNIQUE (group_id, user_id),
    CONSTRAINT fk_group_members_group
        FOREIGN KEY (group_id) REFERENCES groups (id),
    CONSTRAINT fk_group_members_user
        FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_group_members_role CHECK (role IN ('OWNER', 'MEMBER')),
    CONSTRAINT ck_group_members_status CHECK (status IN ('ACTIVE', 'LEFT', 'REMOVED')),
    CONSTRAINT ck_group_members_owner_active CHECK (
        role <> 'OWNER' OR status = 'ACTIVE'
    ),
    CONSTRAINT ck_group_members_left_at CHECK (
        (status = 'ACTIVE' AND left_at IS NULL)
        OR (status IN ('LEFT', 'REMOVED') AND left_at IS NOT NULL)
    ),
    CONSTRAINT ck_group_members_left_after_join CHECK (
        left_at IS NULL OR left_at >= joined_at
    )
);

CREATE UNIQUE INDEX uk_group_members_active_owner
    ON group_members (group_id)
    WHERE role = 'OWNER' AND status = 'ACTIVE';

CREATE INDEX idx_group_members_user_status_joined_at
    ON group_members (user_id, status, joined_at DESC);

CREATE INDEX idx_group_members_group_status_role_joined_at
    ON group_members (group_id, status, role, joined_at);

